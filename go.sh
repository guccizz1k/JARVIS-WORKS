#!/usr/bin/env bash
set -Eeuo pipefail
# JARVIS-WORKS | original-history-only authorized fast-forward push.
# Run from an authenticated GitHub Codespace checkout of guccizz1k/JARVIS-WORKS.
# This script does NOT merge, deploy, modify a DB, create PRs, or force push.
REPO="guccizz1k/JARVIS-WORKS"
BRANCH="review/jw-cinema-pg-engine-20261104"
BASE="84360d3be1c5f5eb5d4d2f8ac5506e96c953611d"
HEAD="d8ee0e70daa0674fdefbf7df2e5a7c42ffcd5ed9"
BUNDLE_SHA="e475394e2e7fbaa3de0a6c922d304d41b2ed69a4716197f821acc2af94adee8e"
EXPECTED=(
 "61af35adb85be0cf176c4c6b5255e865ca56bb4e"
 "edfe760b0826cb7a4b5f1a6c500d425b90f3090c"
 "5db031df01937cff0bdd310a4d5b1a9b48acb0a0"
 "d8ee0e70daa0674fdefbf7df2e5a7c42ffcd5ed9"
)
fail(){ echo "BLOCKED: $*" >&2; exit 1; }
for c in git base64 sha256sum mktemp awk; do command -v "$c" >/dev/null || fail "missing $c"; done
[ "$(git rev-parse --is-inside-work-tree 2>/dev/null)" = true ] || fail "Run inside existing JARVIS-WORKS GitHub Codespace git repository."
origin="$(git remote get-url origin)"
case "$origin" in
  *github.com/guccizz1k/JARVIS-WORKS|*github.com/guccizz1k/JARVIS-WORKS.git|git@github.com:guccizz1k/JARVIS-WORKS|git@github.com:guccizz1k/JARVIS-WORKS.git) ;;
  *) fail "Wrong GitHub origin. Refusing to push: $origin" ;;
esac
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT
# The original Git bundle is bundled as base64 below. No package install needed.
awk '/^__BUNDLE_BASE64_BEGIN__$/{f=1;next} /^__BUNDLE_BASE64_END__$/{f=0} f{print}' "$0" | base64 --decode > "$scratch/approved.bundle"
echo "$BUNDLE_SHA  $scratch/approved.bundle" | sha256sum -c --status || fail 'The embedded Git bundle hash differs from approved bundle.'
echo 'PASS: Original Git bundle SHA-256 verified.'
remote="$(git ls-remote --heads origin "refs/heads/$BRANCH" | awk '{print $1}')"
[ "$remote" = "$BASE" ] || fail "Remote changed (${remote:-missing}); do not overwrite. Expected $BASE."
# Import parent SHA from the public origin, WITHOUT checking out/changing your worktree.
git fetch --no-tags origin "refs/heads/$BRANCH" >/dev/null
[ "$(git rev-parse FETCH_HEAD)" = "$BASE" ] || fail 'Fetched remote base differs.'
git bundle verify "$scratch/approved.bundle" >/dev/null || fail 'Bundle prerequisite or integrity failed.'
git fetch --no-tags "$scratch/approved.bundle" "refs/heads/$BRANCH" >/dev/null
[ "$(git rev-parse FETCH_HEAD)" = "$HEAD" ] || fail 'Bundle head differs from approved HEAD.'
prev="$BASE"
for h in "${EXPECTED[@]}"; do
  [ "$(git rev-parse "$h^")" = "$prev" ] || fail "Unexpected ancestry at $h"
  prev="$h"
done
[ "$(git rev-list --count "$BASE..$HEAD")" = 4 ] || fail 'Expected exactly four commits.'
[ "$(git merge-base "$BASE" "$HEAD")" = "$BASE" ] || fail 'HEAD is not a descendant of base.'
echo "PASS: Four exact approved original commits verified; head=$HEAD"
remote2="$(git ls-remote --heads origin "refs/heads/$BRANCH" | awk '{print $1}')"
[ "$remote2" = "$BASE" ] || fail "Remote changed before push ($remote2)."
# Fast-forward push only; NEVER use --force.
git push origin "$HEAD:refs/heads/$BRANCH"
posted="$(git ls-remote --heads origin "refs/heads/$BRANCH" | awk '{print $1}')"
[ "$posted" = "$HEAD" ] || fail "Post-push ref mismatch: $posted"
echo "PASS: ORIGINAL SHA PUSHED: $HEAD"
echo "GitHub Actions: https://github.com/$REPO/actions?query=branch%3Areview%2Fjw-cinema-pg-engine-20261104"
echo 'PG17 CI outcome requires checking every new workflow run; no DB apply, PR merge or deploy performed.'
exit 0
